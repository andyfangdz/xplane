//! Emit checked Rust basic blocks for compilation by the embedding build.
//! Runtime constants/host operands stay in the VM; no executable memory or
//! machine-code writer is involved. Shape binding chooses the VM on mismatch.
use crate::*;
use std::{
    collections::{BTreeMap, BTreeSet},
    fmt::Write,
};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum GenerateError {
    InvalidRuntimePath,
    InvalidInstruction,
}
/// Rust source and the generated shape index for each input program.
pub struct Generated {
    pub rust: String,
    pub program_ids: Vec<usize>,
}

/// Generate native basic blocks from classified instructions. The caller writes
/// `rust` into its build output and compiles it with rustc. The emitted `shape`
/// and `execute` functions pair with `Vm::bind_aot` / `evaluate_aot`.
/// Only opcodes/arguments are emitted; current literals and host metadata are
/// read at their original instruction points from the VM's owned tables.
pub fn generate(
    programs: &[&[Instruction]],
    runtime_path: &str,
) -> Result<Generated, GenerateError> {
    if runtime_path.is_empty()
        || runtime_path.split("::").any(|part| {
            part.is_empty()
                || !part.bytes().enumerate().all(|(i, c)| {
                    c == b'_' || c.is_ascii_alphabetic() || (i > 0 && c.is_ascii_digit())
                })
        })
    {
        return Err(GenerateError::InvalidRuntimePath);
    }
    let mut shapes = Vec::new();
    let mut seen = BTreeMap::new();
    let mut program_ids = Vec::new();
    for code in programs {
        if code.len() > u32::MAX as usize
            || code.iter().any(|i| {
                i.op >= crate::OP_COUNT
                    || (matches!(i.op, OP_JZ | OP_JUMP) && i.arg == 0)
                    || (matches!(i.op, OP_REG_L | OP_REG_S | OP_REG_SP) && i.arg >= 50)
            })
        {
            return Err(GenerateError::InvalidInstruction);
        }
        let shape: Vec<_> = code.iter().map(|i| (i.op, i.arg)).collect();
        let id = if let Some(&id) = seen.get(&shape) {
            id
        } else {
            let id = shapes.len();
            seen.insert(shape.clone(), id);
            shapes.push(shape);
            id
        };
        program_ids.push(id);
    }
    let mut rust = format!(
        "// Generated by xplane-rpn::aot. Do not edit.\nuse {runtime_path}::{{AotFrame, NumericFrame, Fault, Host, aot}};\n"
    );
    rust.push_str("pub fn shape(id: usize) -> Option<&'static [(u32,u32)]> { match id {\n");
    for (id, shape) in shapes.iter().enumerate() {
        writeln!(rust, "{id} => Some(&{shape:?}),").unwrap();
    }
    rust.push_str("_ => None, }}\n");
    rust.push_str("pub fn execute<H: Host>(id: usize, frame: &mut AotFrame<'_,H>) -> Result<(),Fault<H::Error>> { match id {\n");
    for id in 0..shapes.len() {
        writeln!(rust, "{id} => program_{id}::<H,false>(frame),").unwrap();
    }
    rust.push_str("_ => Err(frame.bad_plan()), }}\n");
    rust.push_str("/// Execute a trusted generated body after source-shape binding and the VM entry guard.\n/// # Safety\n/// id must name the exact shape bound to this frame; use evaluate_aot_prevalidated.\npub unsafe fn execute_prevalidated<H:Host>(id:usize, frame:&mut AotFrame<'_,H>)->Result<(),Fault<H::Error>> { match id {\n");
    for id in 0..shapes.len() {
        writeln!(rust, "{id} => program_{id}::<H,true>(frame),").unwrap();
    }
    rust.push_str("_ => Err(frame.bad_plan()), }}\n");
    for (id, shape) in shapes.iter().enumerate() {
        emit_program(&mut rust, id, shape);
    }
    rust.push_str("/// Execute the exact bound typed numeric plan.\n/// # Safety\n/// Use only with Vm::evaluate_numeric and the matching generated id.\npub unsafe fn execute_numeric<H:Host>(id:usize, frame:&mut NumericFrame<'_,H>)->Result<(),Fault<H::Error>> {match id {\n");
    for (id, shape) in shapes.iter().enumerate() {
        if numeric_heights(shape).is_some() {
            writeln!(rust, "{id}=>numeric_program_{id}(frame),").unwrap();
        }
    }
    rust.push_str("_=>Err(frame.bad_plan()),}}\n");
    for (id, shape) in shapes.iter().enumerate() {
        if let Some(heights) = numeric_heights(shape) {
            emit_typed(&mut rust, id, shape, &heights);
        }
    }
    Ok(Generated { rust, program_ids })
}
fn emit_program(out: &mut String, id: usize, shape: &[(u32, u32)]) {
    writeln!(
        out,
        "#[allow(clippy::never_loop)]\nfn program_{id}<H: Host, const FAST: bool>(frame: &mut AotFrame<'_,H>) -> Result<(),Fault<H::Error>> {{"
    )
    .unwrap();
    if shape.is_empty() {
        out.push_str("let _ = frame; Ok(()) }\n");
        return;
    }
    let count = shape.len() as u64;
    let mut leaders = BTreeSet::from([1u64]);
    for (at, &(op, arg)) in shape.iter().enumerate() {
        let pc = at as u64 + 1;
        if matches!(op, OP_JZ | OP_JUMP | OP_QUIT) {
            if pc < count {
                leaders.insert(pc + 1);
            }
            if op != OP_QUIT && u64::from(arg) <= count {
                leaders.insert(u64::from(arg));
            }
        }
    }
    let starts: Vec<_> = leaders.into_iter().collect();
    let blocks: BTreeMap<_, _> = starts
        .iter()
        .enumerate()
        .map(|(id, &pc)| (pc, id))
        .collect();
    out.push_str("#[allow(unused_mut)] let mut block = 0usize; loop { match block {\n");
    for (block, &first) in starts.iter().enumerate() {
        let end = starts.get(block + 1).copied().unwrap_or(count + 1);
        writeln!(out, "{block} => {{").unwrap();
        let mut pc = first;
        while pc < end {
            let mut stop = pc;
            while stop < end && numeric_op(shape[(stop - 1) as usize].0) {
                stop += 1;
            }
            if stop - pc >= 3
                && shape[(pc - 1) as usize..(stop - 1) as usize]
                    .iter()
                    .any(|&(op, _)| op != OP_PUSH)
            {
                emit_numeric(out, shape, pc, stop);
                pc = stop;
            } else {
                emit_step(out, shape, pc);
                pc += 1;
            }
        }
        let pc = end - 1;
        let (op, arg) = shape[(pc - 1) as usize];
        match op {
            OP_QUIT => out.push_str("return Ok(());\n"),
            OP_JUMP => emit_target(out, u64::from(arg), &blocks),
            OP_JZ if blocks.get(&(pc + 1)) == blocks.get(&u64::from(arg)) => {
                // Both edges have the same successor, but the instruction's
                // pop/comparison still executes before this control transfer.
                emit_target(out, pc + 1, &blocks);
            }
            OP_JZ => {
                writeln!(out, "if frame.next_pc() == {} {{", pc + 1).unwrap();
                emit_target(out, pc + 1, &blocks);
                out.push_str("} else {\n");
                emit_target(out, u64::from(arg), &blocks);
                out.push_str("}\n");
            }
            _ => emit_target(out, end, &blocks),
        }
        out.push_str("}\n");
    }
    out.push_str("_ => return Err(frame.bad_plan()), } } }\n");
}
fn emit_target(out: &mut String, pc: u64, blocks: &BTreeMap<u64, usize>) {
    if let Some(block) = blocks.get(&pc) {
        writeln!(out, "block = {block};").unwrap();
    } else {
        out.push_str("return Ok(());\n");
    }
}

fn emit_step(out: &mut String, shape: &[(u32, u32)], pc: u64) {
    let (op, arg) = shape[(pc - 1) as usize];
    writeln!(out, "if FAST {{\n// SAFETY: the generated bound shape fixes this instruction; the entry guard proves budget.\nunsafe {{ frame.step_prevalidated::<{op},{arg}>({pc})?; }}\n}} else {{ frame.step::<{op},{arg}>({pc})?; }}").unwrap();
}
fn numeric_op(op: u32) -> bool {
    matches!(
        op,
        OP_PUSH | OP_ADD | OP_SUB | OP_MUL | OP_DIV | OP_INC | OP_DEC | OP_NEG | OP_ABS | OP_SQR
    )
}
fn emit_numeric(out: &mut String, shape: &[(u32, u32)], first: u64, end: u64) {
    let mut body = String::new();
    let mut stack: Vec<String> = Vec::new();
    let mut inputs = 0usize;
    let mut delta = 0i64;
    let mut peak = 0i64;
    let mut literals = Vec::new();
    fn pop(stack: &mut Vec<String>, inputs: &mut usize, body: &mut String) -> String {
        stack.pop().unwrap_or_else(|| {
            let name = format!("input_{}", *inputs);
            writeln!(body, "let {name} = frame.numeric_input({});", *inputs).unwrap();
            *inputs += 1;
            name
        })
    }
    for pc in first..end {
        let op = shape[(pc - 1) as usize].0;
        let name = format!("v_{pc}");
        if op == OP_PUSH {
            literals.push(pc as u32);
            writeln!(body,"// SAFETY: this source PUSH is in the bound shape and accepted by numeric_guard.\nlet {name} = aot::normalize(unsafe {{ frame.numeric_literal({pc}) }});").unwrap();
            delta += 1;
        } else if matches!(op, OP_ADD | OP_SUB | OP_MUL | OP_DIV) {
            let b = pop(&mut stack, &mut inputs, &mut body);
            let a = pop(&mut stack, &mut inputs, &mut body);
            writeln!(body, "let {name} = aot::binary::<{op}>({a},{b});").unwrap();
            delta -= 1;
        } else {
            let a = pop(&mut stack, &mut inputs, &mut body);
            writeln!(body, "let {name} = aot::unary::<{op}>({a});").unwrap();
        }
        peak = peak.max(delta);
        stack.push(name);
    }
    writeln!(
        out,
        "if FAST && frame.numeric_guard({inputs},{peak},&{literals:?}) {{"
    )
    .unwrap();
    out.push_str(&body);
    writeln!(out,"// SAFETY: guarded infallible arithmetic follows this exact source region; all outputs were normalized at each source push.\nunsafe {{ frame.numeric_commit({inputs}, &[{}], {}); }}\n}} else {{",stack.join(","),end-1).unwrap();
    writeln!(out,"if FAST {{\n// SAFETY: the bound generated shape identifies this exact contiguous arithmetic region; the VM entry guard proves budget.\nunsafe {{ frame.numeric_fallback({first},{end})?; }}\n}} else {{").unwrap();
    for pc in first..end {
        emit_step(out, shape, pc);
    }
    out.push_str("}}\n");
}

/// Normalize a numeric source push without removing its floating-point status
/// effects when the value is later discarded. Arithmetic remains in source order.
#[doc(hidden)]
#[inline(always)]
pub fn normalize(value: f64) -> f64 {
    #[cfg(target_arch = "x86_64")]
    {
        let mut mask = value;
        // SAFETY: scalar SSE2 is mandatory on x86-64; the asm touches no memory,
        // stack or flags. Like the VM's is_nan comparison it is quiet for qNaN,
        // signals invalid for sNaN and retains denormal-input status effects.
        unsafe {
            core::arch::asm!("cmpunordsd {mask}, {mask}", "andnpd {mask}, {value}",
                mask=inout(xmm_reg) mask, value=in(xmm_reg) value,
                options(nomem,nostack,preserves_flags));
        }
        mask
    }
    #[cfg(not(target_arch = "x86_64"))]
    {
        if value.is_nan() { 0.0 } else { value }
    }
}
/// Shared VM arithmetic, specialized by the Rust compiler for a source opcode.
#[doc(hidden)]
#[inline(always)]
pub fn binary<const OP: u32>(a: f64, b: f64) -> f64 {
    normalize(crate::engine::numeric_binary(OP, a, b))
}
/// Shared VM arithmetic, specialized by the Rust compiler for a source opcode.
#[doc(hidden)]
#[inline(always)]
pub fn unary<const OP: u32>(a: f64) -> f64 {
    normalize(crate::engine::numeric_unary(OP, a))
}

/// Analyze a fresh numeric stack on every path of a forward-only shape.
/// Each entry is the unique incoming stack height, or None for an unreachable
/// instruction or a merge with several heights. None for the whole plan means
/// an unsupported opcode, backward edge, descriptor or peak above 64 slots.
/// Constant types are deliberately checked separately against the actual VM.
pub fn numeric_heights(shape: &[(u32, u32)]) -> Option<Vec<Option<usize>>> {
    if shape.iter().enumerate().any(|(at, &(op, arg))| {
        op >= OP_COUNT
            || matches!(op, OP_SCMP)
            || (matches!(op, OP_JZ | OP_JUMP) && arg as usize <= at + 1)
            || (matches!(op, OP_REG_L | OP_REG_S | OP_REG_SP) && arg >= 50)
    }) {
        return None;
    }
    let mut states = Vec::new();
    states.try_reserve_exact(shape.len().checked_add(1)?).ok()?;
    states.resize(shape.len() + 1, 0u128);
    states[0] = 1;
    for (at, &(op, arg)) in shape.iter().enumerate() {
        let mut incoming = states[at];
        let mut output = 0;
        while incoming != 0 {
            let height = incoming.trailing_zeros() as usize;
            incoming &= incoming - 1;
            if op == OP_CASE {
                // A successful numeric CASE consumes count/index plus at least
                // one candidate, then pushes one. Count may be any valid live
                // value: retain every possible resulting height, never assume
                // the build-time literal is the runtime value.
                if height >= 3 {
                    for after in 1..=height - 2 {
                        output |= 1u128 << after;
                    }
                }
                continue;
            }
            let after = match op {
                OP_PUSH | OP_GET_L | OP_GET_X | OP_REG_L | OP_DUP | OP_PI => height + 1,
                OP_SET_L | OP_SET_K | OP_SET_X | OP_JZ | OP_REG_SP | OP_POP => {
                    height.saturating_sub(1)
                }
                OP_CLEAR => 0,
                OP_SWAP => height.max(2),
                OP_RNG => height.saturating_sub(3) + 1,
                OP_EQ..=OP_OR => height.saturating_sub(2) + 1,
                OP_INC..=OP_RNOR => height.max(1),
                _ => height,
            };
            if after > 64 {
                return None;
            }
            output |= 1u128 << after;
        }
        if matches!(op, OP_JZ | OP_JUMP) && arg as usize <= shape.len() {
            states[arg as usize - 1] |= output;
        }
        if !matches!(op, OP_JUMP | OP_QUIT) {
            states[at + 1] |= output;
        }
    }
    Some(
        states
            .into_iter()
            .take(shape.len())
            .map(|mask| {
                if mask.count_ones() == 1 {
                    Some(mask.trailing_zeros() as usize)
                } else {
                    None
                }
            })
            .collect(),
    )
}
fn emit_typed(out: &mut String, id: usize, shape: &[(u32, u32)], heights: &[Option<usize>]) {
    writeln!(out,"#[allow(clippy::never_loop)]\nfn numeric_program_{id}<H:Host>(frame:&mut NumericFrame<'_,H>)->Result<(),Fault<H::Error>> {{").unwrap();
    if shape.is_empty() {
        out.push_str("let _=frame;Ok(())}\n");
        return;
    }
    let count = shape.len() as u64;
    let mut leaders = BTreeSet::from([1u64]);
    for (at, &(op, arg)) in shape.iter().enumerate() {
        let pc = at as u64 + 1;
        if matches!(op, OP_JZ | OP_JUMP | OP_QUIT) {
            if pc < count {
                leaders.insert(pc + 1);
            }
            if op != OP_QUIT && u64::from(arg) <= count {
                leaders.insert(u64::from(arg));
            }
        }
    }
    let starts: Vec<_> = leaders.into_iter().collect();
    let blocks: BTreeMap<_, _> = starts.iter().enumerate().map(|(i, &pc)| (pc, i)).collect();
    out.push_str("#[allow(unused_mut)] let mut block=0usize;loop {match block {\n");
    for (block, &first) in starts.iter().enumerate() {
        let end = starts.get(block + 1).copied().unwrap_or(count + 1);
        writeln!(out, "{block}=>{{").unwrap();
        for pc in first..end {
            let (op, arg) = shape[(pc - 1) as usize];
            let height = heights[(pc - 1) as usize]
                .map(|h| h.to_string())
                .unwrap_or_else(|| "{usize::MAX}".into());
            writeln!(out,"// SAFETY: the bound source shape and numeric CFG fix this instruction/height; stop on deoptimization.\nif !unsafe {{frame.step::<{op},{arg},{height}>({pc})?}} {{return Ok(());}}").unwrap();
        }
        let pc = end - 1;
        let (op, arg) = shape[(pc - 1) as usize];
        match op {
            OP_QUIT => out.push_str("return Ok(());\n"),
            OP_JUMP => emit_target(out, u64::from(arg), &blocks),
            OP_JZ if blocks.get(&(pc + 1)) == blocks.get(&u64::from(arg)) => {
                // Both edges have the same successor, but the instruction's
                // pop/comparison still executes before this control transfer.
                emit_target(out, pc + 1, &blocks);
            }
            OP_JZ => {
                writeln!(out, "if frame.next_pc()=={} {{", pc + 1).unwrap();
                emit_target(out, pc + 1, &blocks);
                out.push_str("} else {\n");
                emit_target(out, u64::from(arg), &blocks);
                out.push_str("}\n");
            }
            _ => emit_target(out, end, &blocks),
        }
        out.push_str("}\n");
    }
    out.push_str("_=>return Err(frame.bad_plan()),}}}\n");
}
